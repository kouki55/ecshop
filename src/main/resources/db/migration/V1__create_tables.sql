-- 全テーブルの初期定義。
-- 方針：データ設計ルールはアプリだけでなく DB の制約（NOT NULL / 外部キー / 一意 / CHECK）でも守る。
-- このファイルは適用後に書き換えない。変更は V2 以降の新しいファイルで行う。

-- =========================================================
-- 会員
-- =========================================================
CREATE TABLE users (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email              VARCHAR(254) NOT NULL,
    -- bcrypt のハッシュだけを保存する（平文の列は持たない）
    password_hash      VARCHAR(255) NOT NULL,
    name               VARCHAR(100) NOT NULL,
    role               VARCHAR(20)  NOT NULL DEFAULT 'MEMBER',
    status             VARCHAR(20)  NOT NULL DEFAULT 'PENDING',
    failed_login_count INTEGER      NOT NULL DEFAULT 0,
    -- NULL ならロックされていない
    locked_until       TIMESTAMPTZ,
    created_at         TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at         TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ck_users_role CHECK (role IN ('MEMBER', 'ADMIN')),
    CONSTRAINT ck_users_status CHECK (status IN ('PENDING', 'ACTIVE', 'WITHDRAWN')),
    CONSTRAINT ck_users_failed_login_count CHECK (failed_login_count >= 0)
);

-- メールアドレスは大文字・小文字を区別せずに一意（Foo@example.com と foo@example.com は同じ扱い）
CREATE UNIQUE INDEX ux_users_email_lower ON users (lower(email));

-- メール確認・パスワード再設定のトークン（purpose で種類を区別する）
CREATE TABLE user_tokens (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT      NOT NULL,
    purpose    VARCHAR(30) NOT NULL,
    -- トークン本体は保存せず、SHA-256 の 16 進文字列だけを保存する
    token_hash CHAR(64)    NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    -- NULL なら未使用。使ったら日時を入れ、以後は無効
    used_at    TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT fk_user_tokens_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT uq_user_tokens_token_hash UNIQUE (token_hash),
    CONSTRAINT ck_user_tokens_purpose CHECK (purpose IN ('EMAIL_VERIFICATION', 'PASSWORD_RESET')),
    CONSTRAINT ck_user_tokens_expires_at CHECK (expires_at > created_at)
);

CREATE INDEX ix_user_tokens_user_id ON user_tokens (user_id);

-- =========================================================
-- 商品
-- =========================================================
CREATE TABLE categories (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(100) NOT NULL,
    display_order INTEGER      NOT NULL DEFAULT 0,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uq_categories_name UNIQUE (name)
);

CREATE TABLE products (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id BIGINT        NOT NULL,
    name        VARCHAR(200)  NOT NULL,
    description VARCHAR(2000) NOT NULL DEFAULT '',
    -- 税抜単価（円）
    price       BIGINT        NOT NULL,
    -- 税率（%）。軽減税率 8% と標準税率 10% のみ
    tax_rate    INTEGER       NOT NULL,
    stock       INTEGER       NOT NULL,
    -- 商品は削除せず、FALSE（非公開）にする
    published   BOOLEAN       NOT NULL DEFAULT FALSE,
    created_at  TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT fk_products_category FOREIGN KEY (category_id) REFERENCES categories (id),
    CONSTRAINT ck_products_price CHECK (price >= 0),
    CONSTRAINT ck_products_tax_rate CHECK (tax_rate IN (8, 10)),
    CONSTRAINT ck_products_stock CHECK (stock >= 0)
);

CREATE INDEX ix_products_category_id ON products (category_id);

-- =========================================================
-- 配送先
-- =========================================================
CREATE TABLE addresses (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT       NOT NULL,
    recipient_name VARCHAR(100) NOT NULL,
    postal_code    CHAR(7)      NOT NULL,
    prefecture     VARCHAR(10)  NOT NULL,
    city           VARCHAR(100) NOT NULL,
    address_line1  VARCHAR(200) NOT NULL,
    address_line2  VARCHAR(200),
    phone          VARCHAR(11)  NOT NULL,
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT fk_addresses_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT ck_addresses_postal_code CHECK (postal_code ~ '^[0-9]{7}$'),
    CONSTRAINT ck_addresses_phone CHECK (phone ~ '^[0-9]{10,11}$')
);

CREATE INDEX ix_addresses_user_id ON addresses (user_id);

-- =========================================================
-- カート
-- =========================================================
CREATE TABLE carts (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT      NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT fk_carts_user FOREIGN KEY (user_id) REFERENCES users (id),
    -- 会員 1 人につきカートは 1 つ
    CONSTRAINT uq_carts_user_id UNIQUE (user_id)
);

CREATE TABLE cart_items (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cart_id    BIGINT      NOT NULL,
    product_id BIGINT      NOT NULL,
    quantity   INTEGER     NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT fk_cart_items_cart FOREIGN KEY (cart_id) REFERENCES carts (id),
    CONSTRAINT fk_cart_items_product FOREIGN KEY (product_id) REFERENCES products (id),
    -- 同じ商品は 1 行にまとめ、数量で表す
    CONSTRAINT uq_cart_items_cart_product UNIQUE (cart_id, product_id),
    CONSTRAINT ck_cart_items_quantity CHECK (quantity > 0)
);

CREATE INDEX ix_cart_items_product_id ON cart_items (product_id);

-- =========================================================
-- 注文
-- =========================================================
CREATE TABLE orders (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             BIGINT       NOT NULL,
    -- 二重送信で同じ注文が 2 件できないようにするためのキー
    idempotency_key     UUID         NOT NULL,
    status              VARCHAR(20)  NOT NULL DEFAULT 'RECEIVED',
    -- 税抜合計
    subtotal            BIGINT       NOT NULL,
    -- 税率ごとの合計に対して 1 回だけ切り捨てた消費税の合計
    tax_amount          BIGINT       NOT NULL,
    shipping_fee        BIGINT       NOT NULL,
    total_amount        BIGINT       NOT NULL,
    -- 注文時点の配送先のコピー（住所を変更・削除しても過去の注文は変わらない）
    ship_recipient_name VARCHAR(100) NOT NULL,
    ship_postal_code    CHAR(7)      NOT NULL,
    ship_prefecture     VARCHAR(10)  NOT NULL,
    ship_city           VARCHAR(100) NOT NULL,
    ship_address_line1  VARCHAR(200) NOT NULL,
    ship_address_line2  VARCHAR(200),
    ship_phone          VARCHAR(11)  NOT NULL,
    ordered_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT fk_orders_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT uq_orders_idempotency_key UNIQUE (idempotency_key),
    CONSTRAINT ck_orders_status CHECK (status IN ('RECEIVED', 'PAID', 'SHIPPED', 'COMPLETED', 'CANCELLED')),
    CONSTRAINT ck_orders_subtotal CHECK (subtotal >= 0),
    CONSTRAINT ck_orders_tax_amount CHECK (tax_amount >= 0),
    CONSTRAINT ck_orders_shipping_fee CHECK (shipping_fee >= 0),
    CONSTRAINT ck_orders_total_amount CHECK (total_amount = subtotal + tax_amount + shipping_fee),
    CONSTRAINT ck_orders_ship_postal_code CHECK (ship_postal_code ~ '^[0-9]{7}$'),
    CONSTRAINT ck_orders_ship_phone CHECK (ship_phone ~ '^[0-9]{10,11}$')
);

-- 注文履歴（会員ごと・新しい順）の検索用
CREATE INDEX ix_orders_user_id_ordered_at ON orders (user_id, ordered_at DESC);

CREATE TABLE order_items (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id     BIGINT       NOT NULL,
    product_id   BIGINT       NOT NULL,
    -- 注文時点の商品名・単価・税率のコピー（商品を変更しても過去の注文は変わらない）
    product_name VARCHAR(200) NOT NULL,
    unit_price   BIGINT       NOT NULL,
    tax_rate     INTEGER      NOT NULL,
    quantity     INTEGER      NOT NULL,
    CONSTRAINT fk_order_items_order FOREIGN KEY (order_id) REFERENCES orders (id),
    CONSTRAINT fk_order_items_product FOREIGN KEY (product_id) REFERENCES products (id),
    CONSTRAINT uq_order_items_order_product UNIQUE (order_id, product_id),
    CONSTRAINT ck_order_items_unit_price CHECK (unit_price >= 0),
    CONSTRAINT ck_order_items_tax_rate CHECK (tax_rate IN (8, 10)),
    CONSTRAINT ck_order_items_quantity CHECK (quantity > 0)
);

CREATE INDEX ix_order_items_product_id ON order_items (product_id);

-- =========================================================
-- 決済（カード番号は保存しない。疑似決済の取引 ID と状態だけ）
-- =========================================================
CREATE TABLE payments (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id       BIGINT      NOT NULL,
    transaction_id VARCHAR(64) NOT NULL,
    status         VARCHAR(20) NOT NULL,
    amount         BIGINT      NOT NULL,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT fk_payments_order FOREIGN KEY (order_id) REFERENCES orders (id),
    CONSTRAINT uq_payments_transaction_id UNIQUE (transaction_id),
    CONSTRAINT ck_payments_status CHECK (status IN ('SUCCEEDED', 'FAILED')),
    CONSTRAINT ck_payments_amount CHECK (amount > 0)
);

CREATE INDEX ix_payments_order_id ON payments (order_id);

-- 失敗後の再試行は許すが、1 つの注文に「成功」は 1 件だけ
CREATE UNIQUE INDEX ux_payments_order_succeeded ON payments (order_id) WHERE status = 'SUCCEEDED';
